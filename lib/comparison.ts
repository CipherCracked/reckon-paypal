import { products } from "./catalog/products.ts";
import { computeCommitment } from "./commitment/compute.ts";
import { presentFigures } from "./commitment/present.ts";
import { describeSchedule } from "./commitment/schedule.ts";
import { formatMoney, type Currency, type Money } from "./money.ts";
import { measureReadability } from "./readability.ts";

/**
 * Every amount written in the copy, as minor units. The catalogue is USD, so a
 * plain `$1,234.56` is the whole grammar; anything it cannot read is not counted
 * rather than guessed at.
 */
function moneyAmounts(currency: Currency, text: string): Money[] {
  const found = text.match(/\$\s?\d[\d,]*(?:\.\d{2})?/g) ?? [];
  return found.flatMap((match) => {
    // Split the decimal string rather than multiplying by 100, for the same
    // reason `fromDecimalString` does: no amount goes through floating point.
    const [whole, fraction = ""] = match.replace(/[^0-9.]/g, "").split(".");
    const minor = Number(whole) * 100 + Number(fraction.padEnd(2, "0").slice(0, 2));
    return Number.isFinite(minor) ? [{ currency, minor }] : [];
  });
}

/**
 * The evidence IPD 9 asks for: the seller's own words beside the rendering, for
 * every product the app handles, produced by the same functions the screen runs.
 * A hand-written version of this would drift; this one cannot.
 */
export function buildComparison(): string {
  const lines: string[] = [
    "# What the shopper reads, against what the seller wrote",
    "",
    "> Generated by `npm run comparison` from the same functions the app runs. Do not edit by hand —",
    "> the test `tests/comparison.test.ts` fails when this file and the code disagree.",
    "",
    "**What this document is.** A statement of what changes between the merchant's copy and the",
    "screen: which figures appear, in what order, and where each one comes from. It is not proof that",
    "anyone understood either version — no users were tested (IPD 9).",
    "",
    "Two caveats on the numbers below, because they are easy to over-read. **Reading level** is a",
    "syllable count (Flesch–Kincaid): it is unstable below a few hundred words, and near zero for a",
    "list of short lines, so the screen scores low partly because it is a list. It is reported because",
    "it is the one measure computable for both texts — not because a lower grade proves anything.",
    "**Word counts** favour short copy, which is not automatically better copy.",
    "",
  ];

  for (const product of products) {
    const translation = computeCommitment(product.terms);
    const figures = presentFigures(product.terms, translation);
    const merchant = measureReadability(product.description);
    // The screen's own words, measured the same way as the seller's.
    const screenText = figures
      .map((figure) =>
        figure.amount === null
          ? `${figure.label}: Not stated.`
          : `${figure.label}: ${formatMoney(figure.amount)}.`,
      )
      .join(" ");
    const screen = measureReadability(screenText);
    // What the seller actually wrote down, so the table cannot claim they said nothing.
    const stated = moneyAmounts(product.terms.itemPrice.currency, product.description);
    const statedTotals = stated.filter((amount) => amount.minor === translation.acrossTerm.minor);
    const rendered = figures
      .map((figure) =>
        figure.amount === null
          ? `${figure.label}: not stated`
          : `${figure.label}: ${formatMoney(figure.amount)}${
              figure.arithmetic ? ` (${figure.arithmetic})` : ""
            }`,
      )
      .join("; ");

    lines.push(
      `## ${product.name}`,
      "",
      "**The seller says**",
      "",
      `> ${product.description}`,
      "",
      `**The shopper reads**`,
      "",
      ...figures.map(
        (figure) =>
          `- ${figure.label}: ${
            figure.amount === null ? "Not stated" : formatMoney(figure.amount)
          }${figure.arithmetic ? ` — ${figure.arithmetic}` : ""}`,
      ),
      "",
      "| Measure | Seller's copy | This screen |",
      "|---|---|---|",
      `| Words | ${merchant.words} | ${screen.words} |`,
      `| Money amounts written out | ${stated.length} | ${figures.filter((f) => f.amount !== null).length} |`,
      `| Times the cost across the term appears | ${statedTotals.length} | 1 |`,
      `| Reading level (Flesch–Kincaid) | ${merchant.grade} | ${screen.grade} |`,
      "",
      `Rendered as one line: ${rendered}.`,
      "",
      `Schedule: ${describeSchedule(product.terms)}`,
      "",
    );
  }

  lines.push(
    "---",
    "",
    "## What this comparison does and does not show",
    "",
    "- **Shows:** every product's commitment restated as three figures, in a fixed order, each with",
    "  the parts it was built from — including the total across the term, which is the figure no",
    "  seller's copy states and no shopper can work out without doing the multiplication.",
    "- **Does not show:** that a reader understood it better. That needs participants, and the",
    "  product collects nothing about anyone, so the claim is not made.",
    "",
  );

  return lines.join("\n");
}
